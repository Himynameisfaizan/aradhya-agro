        <h3>Raw Material Procurement</h3>
        <p>Fresh, high-quality mustard seeds are sourced directly from our network of 500+ partner farmers at peak ripeness — cutting out middlemen so both farmer and buyer get a fair deal.</p>
      </div>
    </div>

    <div class="flow-step">
      <div class="flow-num">2</div>
      <div class="flow-body">
        <h3>Cleaning</h3>
        <p>Seeds are thoroughly cleaned to remove dust, husk, and foreign matter before they ever reach the press, protecting both flavour and purity downstream.</p>
      </div>
    </div>

    <div class="flow-step">
      <div class="flow-num">3</div>
      <div class="flow-body">
        <h3>Cold Press Extraction</h3>
        <p>Cleaned seeds are slow-crushed in traditional wooden churners (Kachchi Ghani) at low temperature, preserving natural nutrients, aroma, and the characteristic pungency of real mustard oil.</p>
      </div>
    </div>

    <div class="flow-step">
      <div class="flow-num">4</div>
      <div class="flow-body">
        <h3>Natural Filtration</h3>
        <p>No chemical solvents, ever. Oil is clarified using natural sedimentation and multi-layer filtration until it runs clear.</p>
      </div>
    </div>

    <div class="flow-step">
      <div class="flow-num">5</div>
      <div class="flow-body">
        <h3>Lab Testing</h3>
        <p>Every batch is checked in-house for purity, moisture, and quality parameters before it is approved for packing.</p>
      </div>
    </div>

    <div class="flow-step">
      <div class="flow-num">6</div>
      <div class="flow-body">
        <h3>Packing</h3>
        <p>Oil is filled into food-grade glass or PET bottles and heavy-duty canisters, sealed to hygienic, export-ready standards.</p>
      </div>
    </div>

    <div class="flow-step">
      <div class="flow-num">7</div>
      <div class="flow-body">
        <h3>Dispatch</h3>
        <p>Finished stock is dispatched for domestic delivery or loaded into export containers with complete shipping and customs documentation.</p>
      </div>
    </div>

  </div>
